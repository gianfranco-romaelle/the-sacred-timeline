type GenesisTagKind = "cognitive" | "math" | "scientific" | "pipeline";

const tagCategoryByKind = {
  cognitive: "theme",
  math: "method",
  scientific: "discipline",
  pipeline: "theme",
} as const satisfies Record<GenesisTagKind, TagDefinition["category"]>;

const domainIdsByKind = {
  cognitive: ["domain_transmission"],
  math: ["domain_science"],
  scientific: ["domain_science"],
  pipeline: ["domain_transmission"],
} as const satisfies Record<GenesisTagKind, readonly DomainId[]>;

const buildGenesisTags = (labels: readonly string[], kind: GenesisTagKind): TagDefinition[] =>
  labels.map((label) => {
    const slug = slugifyTagLabel(label);
    return {
      id: `tag_genesis_${kind}_${slug}` as TagId,
      slug: `genesis-${kind}-${slug.replaceAll("_", "-")}`,
      label,
      description: `Genesis controlled vocabulary ${kind} tag: ${label}.`,
      category: tagCategoryByKind[kind],
      domainIds: [...domainIdsByKind[kind]],
    };
  });

export const genesisControlledTags: TagDefinition[] = [
  ...buildGenesisTags(GENESIS_COGNITIVE_TAG_LABELS, "cognitive"),
  ...buildGenesisTags(GENESIS_MATH_TAG_LABELS, "math"),
  ...buildGenesisTags(GENESIS_SCIENTIFIC_DOMAIN_LABELS, "scientific"),
  ...buildGenesisTags(GENESIS_PIPELINE_FLAG_LABELS, "pipeline"),
];

