const SCIENTIFIC_SCHOOL_PATTERN =
  /mathemat|geometry|calculus|mechanics|analysis|physics|quantum|relativity|topology|algebra|logic|cybernetics|information|systems|operations|game theory|computer|ai|machine learning|deep learning|data|science|engineering|biotechnology|genomics|bioinformatics|neuroscience|nmr|dynamics|cognitive science/i;

const RELIGIOUS_SCHOOL_PATTERN =
  /vedic|samhita|brahmana|aranyaka|upanishad|vedanta|advaita|nyaya|vaisheshika|samkhya|yoga|tantric|gnostic|patristic|pauline|augustinian|scholastic|thomism|scotism|nominalism|monastery|cathedral|jesuit|kabbalistic|mysticism|islamic|asharism|avicen|averro|confucian|daoist|reformation|rosicrucian|freemason|illuminati|hermetic|esoteric/i;

const PHILOSOPHICAL_SCHOOL_PATTERN =
  /philosophy|platonism|platonic|aristotelian|peripatetic|stoicism|epicureanism|rationalism|empiricism|enlightenment|positivism|idealism|kantian|hegel|phenomenology|hermeneutics|analytic|structuralism|poststructuralism|critical theory|frankfurt|semiotics|psychoanalytic|media theory/i;

const slugifySchoolLabel = (label: string) =>
  label
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();

const inferSchoolDomains = (label: string): DomainId[] => {
  const domains = new Set<DomainId>(["domain_transmission" as DomainId]);

  if (SCIENTIFIC_SCHOOL_PATTERN.test(label)) {
    domains.add("domain_science" as DomainId);
  }

  if (RELIGIOUS_SCHOOL_PATTERN.test(label)) {
    domains.add("domain_religion" as DomainId);
  }

  return Array.from(domains);
};

const inferTraditionType = (label: string): Tradition["traditionType"] => {
  if (/monastery|monastic/i.test(label)) return "monastic";
  if (RELIGIOUS_SCHOOL_PATTERN.test(label)) return "religious";
  if (SCIENTIFIC_SCHOOL_PATTERN.test(label)) return "scientific";
  if (PHILOSOPHICAL_SCHOOL_PATTERN.test(label)) return "philosophical";
  return "intellectual";
};

export const genesisSchoolTraditions: Tradition[] = GENESIS_SCHOOL_LABELS.map((label) => ({
  id: `tradition_${slugifySchoolLabel(label).replace(/-/g, "_")}` as TraditionId,
  entityType: "tradition",
  slug: slugifySchoolLabel(label),
  label,
  description: `${label} from the Genesis controlled Schools vocabulary.`,
  domainIds: inferSchoolDomains(label),
  tagIds: [],
  citationIds: [],
  relatedEntityIds: [],
  mediaAssetIds: [],
  traditionType: inferTraditionType(label),
  placeIds: [],
  institutionIds: [],
  conceptIds: [],
}));
